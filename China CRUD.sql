CREATE TABLE TB_Produtos(
ID_PRODUTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOME_PRODUTO VARCHAR(200) NOT NULL,
LINK_PRODUTO VARCHAR(1000) NOT NULL,
LINK_IMAGEM VARCHAR(1000),
VALOR NUMBER(10,2) NOT NULL,
VALOR_CONVERTIDO NUMBER(10,2),
VALOR_CONVERTIDO_FRETE NUMBER(10,2),
PESO_GRAMAS INT,
DATA_ATUALIZACAO DATE
);

CREATE TABLE TB_FRETE(
ID_FRETE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOME_FRETE VARCHAR(200) NOT NULL,
SERVICO_FRETE VARCHAR(120) DEFAULT 'Nao informado' NOT NULL,
VALOR_100G NUMBER(5,2) NOT NULL,
VALOR_100G_PLUS NUMBER(5,2) NOT NULL,
VALOR_100G_CONVERTIDO NUMBER(5,2),
VALOR_100G_PLUS_CONVERTIDO NUMBER(5,2)
);

CREATE TABLE TB_MODALIDADE(
    ID_MODALIDADE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME_MODALIDADE VARCHAR(200) NOT NULL
);

CREATE TABLE TB_FRETE_MODALIDADE(
    ID_FM NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_FRETE NUMBER NOT NULL,
    ID_MODALIDADE NUMBER NOT NULL,
    FOREIGN KEY (ID_FRETE) REFERENCES TB_FRETE(ID_FRETE),
    FOREIGN KEY (ID_MODALIDADE) REFERENCES TB_MODALIDADE(ID_MODALIDADE)
);

ALTER TABLE TB_FRETE_MODALIDADE 
ADD CONSTRAINT UNIQ_FRETE_MODALIDADE UNIQUE (ID_FRETE, ID_MODALIDADE);

ALTER TABLE TB_PRODUTOS ADD ID_MODALIDADE NUMBER;
ALTER TABLE TB_PRODUTOS ADD CONSTRAINT FK_PROD_MOD FOREIGN KEY (ID_MODALIDADE) REFERENCES TB_MODALIDADE(ID_MODALIDADE);

CREATE TABLE TB_VENDEDORES(
ID_VENDEDOR NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOME_VENDEDOR VARCHAR2(200) NOT NULL,
NOME_LOJA VARCHAR2(200) NOT NULL,
LINK_LOJA VARCHAR2(1000),
ID_USUARIO_CRIADOR NUMBER
);

CREATE TABLE TB_USUARIOS(
ID_USUARIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
NOME_USUARIO VARCHAR2(200) NOT NULL,
USERNAME_USUARIO VARCHAR2(50) NOT NULL,
SENHA_HASH VARCHAR2(255) NOT NULL,
EMAIL_USUARIO VARCHAR2(255),
PERFIL_USUARIO VARCHAR2(20) DEFAULT 'USUARIO' NOT NULL,
TOKEN_VERSION NUMBER DEFAULT 1 NOT NULL,
DATA_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME_USUARIO),
CONSTRAINT UQ_USUARIO_EMAIL UNIQUE (EMAIL_USUARIO),
CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL_USUARIO IN ('ADMIN', 'USUARIO'))
);

CREATE TABLE TB_PASSWORD_RESET(
ID_RESET NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
ID_USUARIO NUMBER NOT NULL,
TOKEN_HASH VARCHAR2(64) NOT NULL,
EXPIRA_EM DATE NOT NULL,
USADO_EM DATE,
IP_SOLICITACAO VARCHAR2(45),
USER_AGENT_SOLICITACAO VARCHAR2(400),
IP_USO VARCHAR2(45),
USER_AGENT_USO VARCHAR2(400),
DATA_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
CONSTRAINT UQ_PASSWORD_RESET_TOKEN UNIQUE (TOKEN_HASH),
CONSTRAINT FK_RESET_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIOS(ID_USUARIO)
);

CREATE INDEX IDX_PASSWORD_RESET_USER ON TB_PASSWORD_RESET (ID_USUARIO, USADO_EM, EXPIRA_EM);

ALTER TABLE TB_PRODUTOS ADD ID_VENDEDOR NUMBER;
ALTER TABLE TB_PRODUTOS ADD CONSTRAINT FK_PROD_VENDEDOR FOREIGN KEY (ID_VENDEDOR) REFERENCES TB_VENDEDORES(ID_VENDEDOR);
ALTER TABLE TB_PRODUTOS ADD ID_USUARIO_CRIADOR NUMBER;
ALTER TABLE TB_PRODUTOS ADD CONSTRAINT FK_PROD_USUARIO_CRIADOR FOREIGN KEY (ID_USUARIO_CRIADOR) REFERENCES TB_USUARIOS(ID_USUARIO);

ALTER TABLE TB_VENDEDORES ADD CONSTRAINT FK_VEND_USUARIO_CRIADOR FOREIGN KEY (ID_USUARIO_CRIADOR) REFERENCES TB_USUARIOS(ID_USUARIO);



