DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLS
     WHERE TABLE_NAME = 'TB_USUARIOS'
       AND COLUMN_NAME = 'EMAIL_USUARIO';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE TB_USUARIOS ADD (EMAIL_USUARIO VARCHAR2(255))';
    END IF;
END;
/

